const all = await (await fetch(`${BASE}/dist/exercises.json`)).json();
const byId = new Map(all.map((e) => [e.id, e]));
const media = {};
let bytes = 0;
for (const [ours, theirs] of Object.entries(MAP)) {
  const e = byId.get(theirs);
  if (!e) throw new Error(`missing ${theirs}`);
  for (const [i, img] of e.images.slice(0, 2).entries()) {
    const buf = Buffer.from(await (await fetch(`${BASE}/exercises/${img}`)).arrayBuffer());
    const out = await sharp(buf).resize({ width: 480, withoutEnlargement: true }).webp({ quality: 72 }).toBuffer();
    fs.writeFileSync(`public/exercises/${ours}-${i}.webp`, out);
    bytes += out.length;
  }
  // Keep the instructions short: first 4 steps, trimmed of boilerplate.
  const steps = e.instructions
    .map((s) => s.replace(/\s+/g, " ").trim())
    .filter((s) => s && !/^repeat for the recommended/i.test(s))
    .slice(0, 4);
  media[ours] = { frames: e.images.slice(0, 2).map((_, i) => `/exercises/${ours}-${i}.webp`), steps, level: e.level };
}
const ts = `// Generated by scripts/fetch-exercise-media.mjs from free-exercise-db (public domain / Unlicense).
export interface ExerciseMedia { frames: string[]; steps: string[]; level: string }
export const EXERCISE_MEDIA: Record<string, ExerciseMedia> = ${JSON.stringify(media, null, 2)};
`;
fs.writeFileSync("src/data/exercise-media.ts", ts);
